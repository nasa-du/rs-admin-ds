#!/usr/bin/env bash
#
# Performance and capacity acceptance (spec §12.6, AC-AUTH-04/AC-OPS-08).
#
# Boots an isolated Compose stack, provisions fixture users through the real
# API, then measures:
#
#   - 20 concurrent password logins        p95 ≤ 1 s
#   - 50 concurrent authenticated reads    p95 ≤ 300 ms
#   - 20 concurrent refreshes of one token p95 ≤ 200 ms, one grace successor,
#                                          no reuse detection
#   - database pool active/max             < 0.8 (sampled from pg_stat_activity)
#
# Usage:
#   ./scripts/perf.sh                 # reset, build if needed, measure, tear down
#   ./scripts/perf.sh --keep          # leave the stack running for debugging
#   ./scripts/perf.sh --no-build      # reuse the local images
#   ./scripts/perf.sh --build         # force an image rebuild
#   ./scripts/perf.sh --out FILE      # write the markdown report (default below)
#   ./scripts/perf.sh --evaluate FILE # render/gate from a saved result JSON
#
# The measurement point is the API listener inside the Compose edge network,
# so the gateway is not in the latency path. Edge latency, TLS and the
# production rate limiter are covered by scripts/check-deploy-edge.sh. Never
# run this against production: it destroys the isolated project's volumes.

set -euo pipefail

# shellcheck source=lib/deploy-check.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib/deploy-check.sh"
# shellcheck source=lib/acceptance.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib/acceptance.sh"
cd "$root"

admin_username="${PERF_ADMIN_USERNAME:-ops.perf}"
admin_email="${PERF_ADMIN_EMAIL:-ops.perf@example.com}"
admin_temp_password="${PERF_ADMIN_TEMP_PASSWORD:-Perf-Bootstrap-Anchor-2026!}"
admin_password="${PERF_ADMIN_PASSWORD:-Perf-Admin-Harbor-2026!}"
user_password="${PERF_USER_PASSWORD:-Perf-Load-Fixture-2026!}"
out="$root/docs/acceptance/performance.md"
keep=0
build_flag=""
evaluate=""

while (($# > 0)); do
    case "$1" in
        --keep) keep=1; shift ;;
        --no-build) build_flag="--no-build"; shift ;;
        --build) build_flag="--build"; shift ;;
        --out) out="${2:?--out requires a path}"; shift 2 ;;
        --evaluate) evaluate="${2:?--evaluate requires a result JSON}"; shift 2 ;;
        --help | -h)
            awk 'NR == 1 { next } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "$0"
            exit 0
            ;;
        *)
            echo "error: unknown argument: $1" >&2
            exit 2
            ;;
    esac
done

export PERF_ADMIN_USERNAME="$admin_username"
export PERF_ADMIN_TEMP_PASSWORD="$admin_temp_password"
export PERF_ADMIN_PASSWORD="$admin_password"
export PERF_USER_PASSWORD="$user_password"

# Perf thresholds are deliberate copies of spec §10.10/§12.6; the renderer
# reports the values carried by the result file.
pool_max_connections=10
api_cpus="${ACCEPTANCE_API_CPUS:-2}"

render_report() {
    local result_file="$1" pool_peak="$2" pool_ratio="$3" pool_ok="$4" pool_samples="$5"
    local generated_at
    generated_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

    jq -r \
        --arg generated_at "$generated_at" \
        --arg pool_peak "$pool_peak" \
        --arg pool_ratio "$pool_ratio" \
        --arg pool_ok "$pool_ok" \
        --arg pool_samples "$pool_samples" \
        --arg pool_max "$pool_max_connections" \
        --arg api_cpus "$api_cpus" '
        def verdict($ok): if $ok then "pass" else "FAIL" end;
        "# Performance and capacity acceptance",
        "",
        "Generated by `scripts/perf.sh` at \($generated_at) UTC.",
        "",
        "## Method",
        "",
        "- Isolated `rs-admin-accept` Compose stack (gateway, web, api, db).",
        "  API CPU limit: \($api_cpus) CPUs; `PASSWORD_HASH_CONCURRENCY=4`; pool",
        "  max \($pool_max) connections per replica; Argon2id m=64 MiB/t=3/p=4.",
        "- Latency is measured at the API listener from a container on the edge",
        "  network; the gateway is therefore not in the latency path. TLS, edge",
        "  rate limiting and static caching are covered by",
        "  `scripts/check-deploy-edge.sh`.",
        "- Fixture users are created through the real admin API and complete the",
        "  forced password change, so every measured session is unrestricted.",
        "- Refreshes are issued concurrently against one session; every response",
        "  must carry the same successor cookie and the reuse counter must not",
        "  move.",
        "",
        "## Result",
        "",
        "| Measurement | Samples | p50 ms | p95 ms | Limit ms | Errors | Verdict |",
        "|---|---|---|---|---|---|---|",
        "| Login (\(.concurrency.login) concurrency) | \(.login.samples) | \(.login.p50_ms) | \(.login.p95_ms) | \(.thresholds.login_p95_ms) | \(.login.errors) | \(verdict(.login.errors == 0 and .login.p95_ms <= .thresholds.login_p95_ms)) |",
        "| API reads (\(.concurrency.api) concurrency) | \(.api.samples) | \(.api.p50_ms) | \(.api.p95_ms) | \(.thresholds.api_p95_ms) | \(.api.errors) | \(verdict(.api.errors == 0 and .api.p95_ms <= .thresholds.api_p95_ms)) |",
        "| Refresh (\(.concurrency.refresh) concurrency) | \(.refresh.samples) | \(.refresh.p50_ms) | \(.refresh.p95_ms) | \(.thresholds.refresh_p95_ms) | \(.refresh.errors) | \(verdict(.refresh.errors == 0 and .refresh.p95_ms <= .thresholds.refresh_p95_ms)) |",
        "",
        "Refresh correctness: \(.refresh.cookie_mismatch_batches) batches with != 1 successor cookie;",
        "reuse-detection delta \(.refresh.reuse_delta).",
        "",
        "Database pool peak: \($pool_peak)/\($pool_max) active connections",
        "(ratio \($pool_ratio), \($pool_samples) samples; target < 0.8) — \(if $pool_ok == "1" then "pass" else "FAIL" end).",
        "Pool gauges at the end of the run: active \(.pool_last.active // "n/a"),",
        "idle \(.pool_last.idle // "n/a"), max \(.pool_last.max // "n/a").",
        "",
        "Setup duration: \(.setup.duration_ms) ms for \(.setup.users) fixture users;",
        "total run \(.duration_ms) ms.",
        "",
        "## Verdict",
        "",
        (if .ok and $pool_ok == "1" then
            "**Pass.** All latency targets and the pool saturation bound were met."
        else
            "**Fail.** At least one target was missed; do not record this run as accepted."
        end),
        "",
        "> This report describes one isolated run on one host. Re-run it on the",
        "> production hardware after any host, container-limit or query-shape",
        "> change, and archive the result with the release record."
    ' "$result_file"
}

print_summary() {
    local result_file="$1" pool_peak="$2" pool_ok="$3"
    jq -r --arg pool_peak "$pool_peak" --arg pool_ok "$pool_ok" '
        "login    p95=\(.login.p95_ms) ms (limit \(.thresholds.login_p95_ms)), errors=\(.login.errors)",
        "api      p95=\(.api.p95_ms) ms (limit \(.thresholds.api_p95_ms)), errors=\(.api.errors)",
        "refresh  p95=\(.refresh.p95_ms) ms (limit \(.thresholds.refresh_p95_ms)), errors=\(.refresh.errors), successor-mismatch batches=\(.refresh.cookie_mismatch_batches), reuse-delta=\(.refresh.reuse_delta)",
        "pool     peak=\($pool_peak)/10 active (target < 8) — \(if $pool_ok == "1" then "pass" else "FAIL" end)"
    ' "$result_file"
}

# Render and gate from an existing result file (also used by script tests).
if [[ -n "$evaluate" ]]; then
    if [[ ! -f "$evaluate" ]]; then
        echo "error: missing result file: $evaluate" >&2
        exit 1
    fi
    pool_peak="${PERF_POOL_PEAK:-0}"
    pool_ratio="$(awk -v peak="$pool_peak" -v max="$pool_max_connections" 'BEGIN { printf "%.2f", peak / max }')"
    pool_ok=0
    awk -v peak="$pool_peak" -v max="$pool_max_connections" 'BEGIN { exit !(peak / max < 0.8) }' && pool_ok=1
    render_report "$evaluate" "$pool_peak" "$pool_ratio" "$pool_ok" "${PERF_POOL_SAMPLES:-0}"
    if ! jq -e '.ok == true' "$evaluate" >/dev/null; then
        exit 1
    fi
    ((pool_ok == 1)) || exit 1
    exit 0
fi

acceptance_require_docker
acceptance_generate_secrets
if [[ -n "$build_flag" ]]; then
    acceptance_ensure_images "$build_flag"
else
    acceptance_ensure_images
fi

teardown() {
    local status=$?
    # Stop the pg_stat_activity sampler and remove its temporary files even
    # when the run is interrupted before the normal cleanup.
    if [[ -n "${sampler_pid:-}" ]]; then
        kill "$sampler_pid" >/dev/null 2>&1 || true
        wait "$sampler_pid" 2>/dev/null || true
    fi
    [[ -n "${sampler_file:-}" ]] && rm -f "$sampler_file"
    [[ -n "${perf_log:-}" ]] && rm -f "$perf_log"
    [[ -n "${result_file:-}" ]] && rm -f "$result_file"
    if ((keep == 0)); then
        acceptance_down
    else
        echo "==> stack kept; stop it with:" >&2
        acceptance_stop_hint
    fi
    exit "$status"
}
trap teardown EXIT

acceptance_up

echo "==> bootstrapping the acceptance administrator"
if ! acceptance_bootstrap "$admin_username" "$admin_email" "$admin_temp_password" >/dev/null; then
    echo "error: bootstrap failed" >&2
    acceptance_compose logs --tail=120 api migrate db >&2 || true
    exit 1
fi

# Sample the runtime role's active connections from PostgreSQL while the load
# generator runs. The metrics gauge refreshes every 15 s, which is too coarse
# to catch a 50-request burst; pg_stat_activity is the authoritative source.
sampler_file="$(mktemp)"
sampler_pid=""
start_sampler() {
    (
        while :; do
            acceptance_psql -tAc \
                "SELECT count(*) FROM pg_stat_activity
                 WHERE usename = 'rs_admin_runtime' AND state = 'active'" \
                2>/dev/null || true
            sleep 0.1
        done
    ) >"$sampler_file" &
    sampler_pid=$!
}
stop_sampler() {
    if [[ -n "$sampler_pid" ]]; then
        kill "$sampler_pid" >/dev/null 2>&1 || true
        wait "$sampler_pid" 2>/dev/null || true
        sampler_pid=""
    fi
}

perf_log="$(mktemp)"
echo "==> running the load generator"
start_sampler
set +e
perf_output="$(acceptance_compose --profile acceptance run --rm -T perf 2>"$perf_log")"
perf_status=$?
set -e
stop_sampler

if [[ -s "$perf_log" ]]; then
    sed 's/^/    /' "$perf_log" >&2
fi

result_json="$(printf '%s\n' "$perf_output" | tail -n 1)"
if ! jq -e '.thresholds and .login and .api and .refresh' >/dev/null 2>&1 <<<"$result_json"; then
    echo "error: the load generator did not produce a valid result (exit $perf_status)" >&2
    printf '%s\n' "$perf_output" >&2
    exit 1
fi

result_file="$(mktemp)"
printf '%s\n' "$result_json" >"$result_file"

pool_peak="$(awk 'NF { if ($1 + 0 > max) max = $1 + 0 } END { print max + 0 }' "$sampler_file")"
pool_samples="$(awk 'NF { count += 1 } END { print count + 0 }' "$sampler_file")"
pool_ratio="$(awk -v peak="$pool_peak" -v max="$pool_max_connections" 'BEGIN { printf "%.2f", peak / max }')"
pool_ok=0
if awk -v peak="$pool_peak" -v max="$pool_max_connections" 'BEGIN { exit !(peak / max < 0.8) }'; then
    pool_ok=1
fi

echo "==> results"
print_summary "$result_file" "$pool_peak" "$pool_ok"
render_report "$result_file" "$pool_peak" "$pool_ratio" "$pool_ok" "$pool_samples" >"$out"
cp "$result_file" "${out%.md}.json"
echo "==> wrote $out and ${out%.md}.json"

if ((perf_status != 0)); then
    echo "error: one or more latency/refresh targets failed" >&2
    exit 1
fi
if ((pool_ok == 0)); then
    echo "error: database pool saturation exceeded 0.8" >&2
    exit 1
fi
